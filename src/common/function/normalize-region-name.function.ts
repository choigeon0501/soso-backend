/**
 * @param region1DepthName Kakao 주소 응답의 시/도 이름 (축약형/전체명 모두 허용)
 * @returns region 테이블 표준 이름(2자). 매칭되는 시/도가 없으면 null.
 */
export function normalizeRegionName(region1DepthName?: string | null): string | null {
  if (!region1DepthName) return null;
  return REGION_NAME_MAP[region1DepthName.trim()] ?? null;
}
